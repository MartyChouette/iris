/// <summary>
/// Categories for keyword highlighting in text.
/// Each category gets its own color in the KeywordHighlighter.
/// </summary>
public enum KeywordCategory
{
    Like,        // things the date enjoys — warm pink
    Dislike,     // things the date avoids — cool grey-blue
    Hobby,       // activities/interests — gold
    Personality, // character traits — soft purple
    Special      // unique/secret keywords — teal
}
